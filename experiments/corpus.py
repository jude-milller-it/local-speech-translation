def long_text(n_sentences: int) -> str:
    """由多样句子构造的长文本（含句末标点）。"""
    return "".join(DIVERSE_SENTENCES[:n_sentences])


def long_no_punct(n_chars: int) -> str:
    """不含任何句末标点的超长连续文本（用于触发硬切）。"""
    base = "人工智能技术的快速发展正在深刻改变人们的生活方式"
    return _repeat(base, (n_chars // len(base)) + 1)[:n_chars]


